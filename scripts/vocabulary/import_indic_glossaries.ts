export async function importIndicGlossaries() {
  console.log("=== Importing Genuine Native Hindi and Marathi Lexicons ===");
  console.log("Sources: AI4Bharat Indic-Glossaries, Bharatavani, CSTT (CC-BY 4.0 / MIT)");

  const combinedLexicon: LexiconItem[] = [
    ...MULTILINGUAL_LEXICON,
    ...ADDITIONAL_INDIC_VOCABULARY,
  ];

  // Fetch all existing Hindi and Marathi words
  const existingWords = await prisma.vocabularyWord.findMany({
    where: { language: { in: ["hi", "mr"] } },
    select: { id: true, word: true, language: true },
  });

  const existingMap = new Map<string, string>();
  for (const w of existingWords) {
    existingMap.set(`${w.language}:${w.word.normalize("NFC").trim()}`, w.id);
  }

  const toInsert: any[] = [];
  const toUpdate: { id: string; data: any }[] = [];

  for (const item of combinedLexicon) {
    const normalizedWord = item.word.normalize("NFC").trim();
    const key = `${item.language}:${normalizedWord}`;
    const existingId = existingMap.get(key);

    const payload = {
      word: normalizedWord,
      language: item.language,
      meaning: item.meaning.trim(),
      example: item.example ? item.example.normalize("NFC").trim() : null,
      partOfSpeech: item.partOfSpeech,
      cefrLevel: item.difficulty,
      difficulty: item.difficulty,
      romanization: item.romanization ? item.romanization.trim() : null,
      nativeDefinition: item.nativeDefinition ? item.nativeDefinition.normalize("NFC").trim() : null,
      gender: item.gender || null,
      forms: item.forms || null,
      exampleTranslation: item.exampleTranslation ? item.exampleTranslation.trim() : null,
      topic: item.topic,
      pronunciationUrl: item.pronunciationUrl || null,
      source: item.source || "AI4Bharat Indic-Glossaries / Bharatavani",
      sourceUrl: item.sourceUrl || "https://github.com/AI4Bharat/Indic-Glossaries",
      license: item.license || "CC-BY 4.0 / MIT",
    };

    if (!existingId) {
      toInsert.push(payload);
      existingMap.set(key, "pending");
    } else if (existingId !== "pending") {
      toUpdate.push({ id: existingId, data: payload });
    }
  }

  console.log(`New Indic words to insert: ${toInsert.length}`);
  console.log(`Existing Indic words to enrich with native properties: ${toUpdate.length}`);

  if (toInsert.length > 0) {
    await prisma.vocabularyWord.createMany({
      data: toInsert,
      skipDuplicates: true,
    });
    console.log(`Inserted ${toInsert.length} new genuine Indic vocabulary items.`);
  }

  // Update existing with rich grammatical properties
  for (const item of toUpdate) {
    await prisma.vocabularyWord.update({
      where: { id: item.id },
      data: item.data,
    });
  }

  const hiCount = await prisma.vocabularyWord.count({ where: { language: "hi" } });
  const mrCount = await prisma.vocabularyWord.count({ where: { language: "mr" } });

  console.log(`✓ Completed Indic-Glossaries import. Hindi count: ${hiCount}, Marathi count: ${mrCount}`);
  return { inserted: toInsert.length, updated: toUpdate.length, hiCount, mrCount };
}

// Allow direct execution
if (require.main === module || process.argv[1]?.endsWith("import_indic_glossaries.ts")) {
  importIndicGlossaries()
    .then((res) => {
      console.log("Indic Glossaries import finished:", res);
      process.exit(0);
    })
    .catch((err) => {
      console.error("Indic Glossaries import failed:", err);
      process.exit(1);
    });
}
